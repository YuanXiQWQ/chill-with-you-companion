// 重新生成 game/src/AnimIdMap.cs —— 数字 id 到 clip 名的映射表。
//
// 来源必须是「干净的一段」：BepInEx/chill-cmd-out.txt 里
//   enum HeroineService
// 会展开出 Bulbul.HeroineService+AnimationType 和 +RoomPlace 两个枚举，
// 而且 MatchTypes 可能让同一段出现两次。所以这里按段解析，只取第一段 AnimationType。
//
// 之前那张表只有 179 条，比真实枚举少了；漏掉的 id 在 DLL 里表现为
// "数字 id 找不到对应 clip，静默跳过"，看不出报错。
//
// 用法：node tools/gen-animmap.mjs [dump.txt] [out.cs]
import fs from 'node:fs'

// 仓库根现算：发布体检不允许代码里出现字面量盘符。
const ROOT = process.env.CHILL_REPO || new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
const DUMP = process.argv[2] || ROOT + '/data/anim-type-dump.txt'
const OUT = process.argv[3] || ROOT + '/game/src/AnimIdMap.cs'

const lines = fs.readFileSync(DUMP, 'utf8').split('\n')

// 只取第一段 HeroineService+AnimationType
const entries = []
let inSection = false
let done = false
for (const raw of lines) {
  const l = raw.replace(/\r$/, '')
  if (/^E /.test(l)) {
    if (inSection) { done = true; break }
    if (/HeroineService\+AnimationType/.test(l)) inSection = true
    continue
  }
  if (!inSection) continue
  const m = l.match(/^\s*([A-Za-z_]\w*)=(-?\d+)\s*$/)
  if (m) entries.push({ name: m[1], id: Number(m[2]) })
}
if (done === false && !inSection) {
  throw new Error('没找到 Bulbul.HeroineService+AnimationType 段：' + DUMP)
}

// 负 id 是哨兵（NotChange），DLL 不会拿它去播放，混进来只会让表看起来更全
const playable = entries.filter((e) => e.id >= 0)
const dropped = entries.filter((e) => e.id < 0)

// 同一个 id 出现两次说明 dump 里还有拼接，先报出来别默默覆盖
const byId = new Map()
const dup = []
for (const e of playable) {
  if (byId.has(e.id)) dup.push(e.id + '=' + byId.get(e.id) + '/' + e.name)
  else byId.set(e.id, e.name)
}
if (dup.length) throw new Error('id 重复，dump 可能仍有多段：' + dup.slice(0, 5).join(', '))

const sorted = [...byId.entries()].sort((a, b) => a[0] - b[0])

const body = sorted.map(([id, name]) => `            { ${id}, "${name}" },`).join('\n')
// 反转表：名字 -> id。DLL 两端都要用（后端可能给名字也可能给数字）。
const revBody = sorted.map(([id, name]) => `            { "${name}", ${id} },`).join('\n')

const cs = `// <auto-generated>
// 由 tools/gen-animmap.mjs 从游戏程序集枚举生成，勿手改。
// 来源：Bulbul.HeroineService/AnimationType（${sorted.length} 条）
// 作用：把后端下发的数字 id 还原成 Animator 的 state/clip 名，全程不引用 Assembly-CSharp。
// </auto-generated>
using System.Collections.Generic;

namespace ChillPerformer
{
    internal static class AnimIdMap
    {
        internal static readonly Dictionary<int, string> ById = new Dictionary<int, string>
        {
${body}
        };

        internal static readonly Dictionary<string, int> ByName = new Dictionary<string, int>
        {
${revBody}
        };

        internal static string Resolve(string idOrName)
        {
            if (string.IsNullOrEmpty(idOrName)) return null;
            int id;
            if (int.TryParse(idOrName, out id))
            {
                string name;
                return ById.TryGetValue(id, out name) ? name : null;
            }
            return idOrName;
        }
    }
}
`

fs.writeFileSync(OUT, cs, 'utf8')
console.log('枚举段 ' + entries.length + ' 条，可播放 ' + sorted.length + ' 条，丢弃哨兵 ' +
  (dropped.length ? dropped.map((d) => d.name + '=' + d.id).join(',') : '0') + ' 条')
console.log('id 范围 ' + sorted[0][0] + ' .. ' + sorted[sorted.length - 1][0])
console.log('written -> ' + OUT)
