import fs from 'node:fs'

const DUMP = process.argv[2] || 'game-enums.txt'
const OUT = process.argv[3] || 'AnimIdMap.cs'
const ENUM = 'Bulbul.HeroineService/AnimationType'

const lines = fs.readFileSync(DUMP, 'utf8').split(/\r?\n/)
let current = null
const pairs = []
for (const line of lines) {
  if (line.startsWith('## ')) {
    current = line.slice(3).replace(/\s+\[\d+\]\s*$/, '').trim()
    continue
  }
  if (current !== ENUM || !line.includes(' = ')) continue
  const [name, raw] = line.split(' = ')
  const id = Number(raw.trim())
  if (!Number.isFinite(id) || id < 0) continue
  if (name.trim() === 'Count') continue
  pairs.push([id, name.trim()])
}
pairs.sort((a, b) => a[0] - b[0])

const ids = pairs.map(([id, name]) => `            { ${id}, "${name}" },`).join('\n')
const names = pairs.map(([id, name]) => `            { "${name}", ${id} },`).join('\n')

const src = `// <auto-generated>
// 由 tools/gen-animmap.mjs 从游戏程序集枚举生成，勿手改。
// 来源：${ENUM}（${pairs.length} 条）
// 作用：把后端下发的数字 id 还原成 Animator 的 state/clip 名，全程不引用 Assembly-CSharp。
// </auto-generated>
using System.Collections.Generic;

namespace ChillPerformer
{
    internal static class AnimIdMap
    {
        internal static readonly Dictionary<int, string> ById = new Dictionary<int, string>
        {
${ids}
        };

        internal static readonly Dictionary<string, int> ByName = new Dictionary<string, int>
        {
${names}
        };

        internal static string Resolve(string idOrName)
        {
            if (string.IsNullOrEmpty(idOrName)) return null;
            int id;
            if (int.TryParse(idOrName, out id))
            {
                string name;
                return ById.TryGetValue(id, out name) ? name : null;
            }
            return idOrName;
        }
    }
}
`
fs.mkdirSync(OUT.replace(/[\\/][^\\/]+$/, '') || '.', { recursive: true })
fs.writeFileSync(OUT, src, 'utf8')
console.log(JSON.stringify({ out: OUT, count: pairs.length, bytes: Buffer.byteLength(src), first: pairs[0], last: pairs[pairs.length - 1] }))
